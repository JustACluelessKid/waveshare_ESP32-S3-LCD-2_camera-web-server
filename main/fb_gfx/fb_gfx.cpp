#define RGB565_MASK_RED    0xF800
#define RGB565_MASK_GREEN  0x07E0
#define RGB565_MASK_BLUE   0x001F

#define COLOR_RGB888_TO_RGB565(r, g, b) ((((r & 0xF8) >> 3) << 11) | (((g & 0xFC) >> 2) << 5) | ((b & 0xF8) >> 3))
#define COLOR_RGB565_TO_RGB888(c, r, g, b) { r = (((c & RGB565_MASK_RED) >> 11) << 3); g = (((c & RGB565_MASK_GREEN) >> 5) << 2); b = ((c & RGB565_MASK_BLUE) << 3); }

#define CONVERT_RGB888_TO_RGB565(r, g, b) ((((r >> 3) & 0x1F) << 11) | (((g >> 2) & 0x3F) << 5) | ((b >> 3) & 0x1F))
#define CONVERT_RGB565_TO_RGB888(c) { ((c & 0xF800) >> 8), ((c & 0x7E0) >> 3), ((c & 0x1F) << 3) }

